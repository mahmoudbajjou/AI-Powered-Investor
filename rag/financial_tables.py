import re


INCOME = "income"
BALANCE = "balance"
CASH_FLOW = "cash_flow"

STATEMENT_HEADINGS = {
    INCOME: r"(?:consolidated )?(?:income statements?|statements? of (?:operations|income|earnings))",
    BALANCE: r"(?:consolidated )?(?:balance sheets?|statements? of financial position)",
    CASH_FLOW: r"(?:consolidated )?(?:cash flows? statements?|statements? of cash flows?)",
}

METRIC_ROWS = {
    INCOME: {
        "revenue": r"(?:total )?(?:net sales|revenues?)",
        "net_income": r"net (?:income(?: \(loss\))?|loss)",
        "operating_income": r"(?:operating (?:income(?: \(loss\))?|loss)|(?:income|loss) from operations)",
    },
    BALANCE: {
        "total_assets": r"total assets",
        "total_liabilities": r"total liabilities",
    },
    CASH_FLOW: {
        "cash_flow": (
            r"(?:net )?cash (?:from operations|"
            r"(?:from|generated by|provided by(?: \(used in\))?|used in) operating activities)"
        ),
    },
}
AMOUNT_FIELDS = tuple(field for fields in METRIC_ROWS.values() for field in fields)

HEADING = re.compile(r"(?m)^#{1,6}[ \t]+(?![ \t*_]*\()")
CELL_BREAK = re.compile(r"<br\s*/?>", re.IGNORECASE)
YEAR = re.compile(r"(?:(?:19|20|21)\d{2})")
DATED_YEAR = re.compile(rf"[A-Za-z]{{3,9}}\.?\s+\d{{1,2}},\s*({YEAR.pattern})")
PERIOD_LABEL = re.compile(
    r"^(?:years?\b|fiscal\b|as of\b|january\b|february\b|march\b|april\b|may\b|june\b|"
    r"july\b|august\b|september\b|october\b|november\b|december\b)",
    re.IGNORECASE,
)
SCALE = re.compile(r"\bin\s+(thousands|millions|billions)\b", re.IGNORECASE)
CURRENCY = re.compile(r"^(?:US\$|CA\$|C\$|AU\$|A\$|HK\$|[$€£¥])")
DIGITS = r"(?:[0-9]{1,3}(?:,[0-9]{3})+|[0-9]+)(?:\.[0-9]+)?"
AMOUNT = re.compile(rf"(?:-?{DIGITS}|\({DIGITS}\))")


def _cell_parts(cell: str) -> list[str]:
    return [part.strip() for part in CELL_BREAK.split(cell.replace("**", "")) if part.strip()]


def _cell_years(cell: str) -> tuple[int, ...]:
    parts = _cell_parts(cell)
    dates = tuple(int(match[1]) for part in parts if (match := DATED_YEAR.fullmatch(part)))
    if dates:
        return dates
    for part in parts[:2]:
        if YEAR.fullmatch(part):
            return (int(part),)
    return ()


def _year_header(rows: list[list[str]]) -> tuple[int, dict[int, tuple[int, ...]]]:
    for index, row in enumerate(rows[:8]):
        labels = _cell_parts(row[0])
        if labels and not PERIOD_LABEL.match(labels[0]):
            continue
        columns = {
            column: periods
            for column, cell in enumerate(row[1:], start=1)
            if (periods := _cell_years(cell))
        }
        distinct_years = {year for periods in columns.values() for year in periods}
        if len(distinct_years) >= 2 or (columns and len(columns) == sum(bool(cell.strip()) for cell in row[1:])):
            return index, columns
    return 0, {}


def _cell_amount(cell: str, label_index: int, label_count: int) -> str | None:
    parts = _cell_parts(cell)
    if parts and CURRENCY.fullmatch(parts[0]):
        parts = parts[1:]
    if not parts or (label_index and label_count != len(parts)):
        return None
    value = CURRENCY.sub("", parts[label_index]).replace("−", "-").strip()
    return value if AMOUNT.fullmatch(value) else None


def _row_amount(
    row: list[str], years: dict[int, tuple[int, ...]], year: int, label_index: int, label_count: int
) -> str | None:
    periods = [period for cell_periods in years.values() for period in cell_periods]
    distinct_periods = list(dict.fromkeys(periods))
    if len(distinct_periods) < len(periods):
        # PDF conversion can duplicate merged year headers and shift their columns.
        if any(len(cell_periods) > 1 for cell_periods in years.values()):
            return None
        amounts = [
            amount for cell in row[1:]
            if (amount := _cell_amount(cell, label_index, label_count)) is not None
        ]
        if len(amounts) == len(distinct_periods):
            return amounts[distinct_periods.index(year)]
        return None

    column, cell_periods = next((column, periods) for column, periods in years.items() if year in periods)
    if column >= len(row):
        return None
    if len(cell_periods) == 1:
        return _cell_amount(row[column], label_index, label_count)

    # Some converted tables stack several fiscal years within one Markdown cell.
    parts = _cell_parts(row[column])
    if label_count == 1 and len(parts) == len(cell_periods):
        return _cell_amount(parts[cell_periods.index(year)], 0, 1)
    return None


def extract_table_amounts(markdown: str, year: int | None) -> dict[str, str]:
    """Read amounts from the primary financial statements for one fiscal year."""
    amounts: dict[str, set[str]] = {}
    for section in HEADING.split(markdown)[1:]:
        heading, _, body = section.partition("\n")
        title = heading.replace("**", "").split("(", 1)[0].strip().lower()
        statement = next(
            (
                key for key, pattern in STATEMENT_HEADINGS.items()
                if re.search(rf"(?:^|\b(?=consolidated ))(?:{pattern})$", title)
            ),
            None,
        )
        if statement is None:
            continue

        rows = [
            line[1:-1].split("|")
            for raw_line in body.splitlines()
            if (line := raw_line.strip()).startswith("|") and line.endswith("|")
        ]
        header, years = _year_header(rows)
        if not years:
            continue
        periods = {period for cell_periods in years.values() for period in cell_periods}
        if year is None:
            year = max(periods)
        if year not in periods:
            continue

        scale = SCALE.search(section)
        currencies = {
            match.group()
            for row in rows
            for cell in row[1:]
            for part in _cell_parts(cell)
            if (match := CURRENCY.match(part))
        }
        if scale is None or len(currencies) != 1:
            continue
        currency = currencies.pop()
        unit = scale[1].lower().removesuffix("s")

        for row in rows[header + 1:]:
            labels = _cell_parts(row[0])
            for label_index, label in enumerate(labels):
                for field, pattern in METRIC_ROWS[statement].items():
                    if not re.fullmatch(pattern, label.rstrip(":"), re.IGNORECASE):
                        continue
                    value = _row_amount(row, years, year, label_index, len(labels))
                    if value is not None:
                        amounts.setdefault(field, set()).add(f"{currency}{value} {unit}")
    return {field: values.pop() for field, values in amounts.items() if len(values) == 1}
